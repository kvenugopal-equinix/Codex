"""Event IDs survive schema upgrades and identify visits rather than display names."""
import csv
import os
from pathlib import Path
import subprocess
import sys
from uuid import UUID

import pytest

import warroom.joinlog as joinlog


def _write(path, header, rows):
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(header)
        writer.writerows(rows)


def _rows(path):
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def _legacy_row(header, name="Visitor"):
    return [name if field == "participant_name" else "" for field in header]


def test_new_event_has_bot_generated_uuid_and_return_matches_saved_row(tmp_path):
    path = tmp_path / "joins.csv"
    event = joinlog.log_join(path, participant_name="Visitor")
    assert UUID(event["event_id"]).version == 4
    assert _rows(path)[0] == event


def test_repeated_name_and_identical_timestamp_get_distinct_ids(tmp_path, monkeypatch):
    from datetime import datetime, timezone

    class FrozenTime:
        @staticmethod
        def now(tz):
            return datetime(2026, 10, 15, 12, 0, 0, tzinfo=timezone.utc)

    monkeypatch.setattr(joinlog, "datetime", FrozenTime)
    path = tmp_path / "joins.csv"
    events = [joinlog.log_join(path, participant_name="Visitor") for _ in range(3)]
    assert len({event["joined_at_utc"] for event in events}) == 1
    assert len({event["event_id"] for event in events}) == 3


@pytest.mark.parametrize("old_header", [joinlog.FIELDS[:-1], joinlog.FIELDS[:-2]])
def test_legacy_rows_get_ids_once_and_keep_their_values(tmp_path, old_header):
    path = tmp_path / "joins.csv"
    before_rows = [_legacy_row(old_header, "Same Visitor") for _ in range(2)]
    _write(path, old_header, before_rows)
    first = joinlog.log_join(path, participant_name="New Visitor")
    rows = _rows(path)
    ids = [row["event_id"] for row in rows]
    assert len(set(ids)) == 3
    assert all(UUID(value).version == 4 for value in ids)
    assert [[row[field] for field in old_header] for row in rows[:2]] == before_rows
    assert rows[2]["event_id"] == first["event_id"]
    joinlog.log_join(path, participant_name="Another Visitor")
    assert [row["event_id"] for row in _rows(path)[:3]] == ids


def test_current_schema_backfills_missing_ids_and_preserves_existing_ids(tmp_path):
    path = tmp_path / "joins.csv"
    saved_id = "380dbfe4-2818-4413-8649-ef07dba71738"
    first = _legacy_row(joinlog.FIELDS, "First")
    first[-1] = saved_id
    _write(path, joinlog.FIELDS, [first, _legacy_row(joinlog.FIELDS, "Second")])
    assert joinlog._migrate(path) == joinlog.FIELDS
    rows = _rows(path)
    assert rows[0]["event_id"] == saved_id
    assert UUID(rows[1]["event_id"]).version == 4
    before = path.read_bytes()
    timestamp = path.stat().st_mtime_ns
    assert joinlog._migrate(path) == joinlog.FIELDS
    assert path.read_bytes() == before
    assert path.stat().st_mtime_ns == timestamp


def test_blank_lines_do_not_become_events_during_migration(tmp_path):
    path = tmp_path / "joins.csv"
    header = joinlog.FIELDS[:-1]
    _write(path, header, [_legacy_row(header), [], []])
    joinlog.log_join(path, participant_name="Next Visitor")
    assert len(_rows(path)) == 2


@pytest.mark.parametrize("supplied_id", ["custom", "", None])
def test_callers_cannot_supply_or_reuse_an_event_id(tmp_path, supplied_id):
    path = tmp_path / "joins.csv"
    with pytest.raises(ValueError, match="generated by the bot"):
        joinlog.log_join(path, participant_name="Visitor", event_id=supplied_id)
    assert not path.exists()


@pytest.mark.parametrize("contents", ["a,b,c\n1,2,3\n", "\n", "event_id,participant_name\nx,A\n"])
def test_nonempty_unknown_schema_refuses_append_without_changing_file(tmp_path, contents):
    path = tmp_path / "joins.csv"
    path.write_text(contents)
    before = path.read_bytes()
    with pytest.raises(ValueError, match="unrecognized header"):
        joinlog.log_join(path, participant_name="Visitor")
    assert path.read_bytes() == before


def test_duplicate_existing_ids_refuse_append_without_changing_file(tmp_path):
    path = tmp_path / "joins.csv"
    values = _legacy_row(joinlog.FIELDS)
    values[-1] = "380dbfe4-2818-4413-8649-ef07dba71738"
    _write(path, joinlog.FIELDS, [values, values])
    before = path.read_bytes()
    with pytest.raises(ValueError, match="repeats an event_id"):
        joinlog.log_join(path, participant_name="Visitor")
    assert path.read_bytes() == before


def test_overwide_row_is_not_truncated_by_migration(tmp_path):
    path = tmp_path / "joins.csv"
    header = joinlog.FIELDS[:-1]
    _write(path, header, [_legacy_row(header) + ["unexpected"]])
    before = path.read_bytes()
    with pytest.raises(ValueError, match="more values than its header"):
        joinlog.log_join(path, participant_name="Visitor")
    assert path.read_bytes() == before


@pytest.mark.parametrize("header", [joinlog.FIELDS, joinlog.FIELDS[:-1]])
def test_failed_id_migration_never_appends_an_unidentifiable_event(tmp_path, monkeypatch, header):
    path = tmp_path / "joins.csv"
    _write(path, header, [_legacy_row(header)])
    before = path.read_bytes()

    def blocked(*args):
        raise PermissionError("file is busy")

    monkeypatch.setattr(joinlog.os, "replace", blocked)
    with pytest.raises(OSError, match="event IDs"):
        joinlog.log_join(path, participant_name="Visitor")
    assert path.read_bytes() == before
    assert not list(tmp_path.glob("*.migrating.*"))


def test_migration_preserves_log_permissions(tmp_path):
    if os.name == "nt":
        pytest.skip("Windows does not expose POSIX permission bits")
    path = tmp_path / "joins.csv"
    header = joinlog.FIELDS[:-1]
    _write(path, header, [_legacy_row(header)])
    path.chmod(0o600)
    joinlog.log_join(path, participant_name="Visitor")
    assert path.stat().st_mode & 0o777 == 0o600


def test_concurrent_local_writers_migrate_once_without_lost_events(tmp_path):
    path = tmp_path / "joins.csv"
    header = joinlog.FIELDS[:-1]
    _write(path, header, [_legacy_row(header)])
    code = """from pathlib import Path
import sys
from warroom.joinlog import log_join
for index in range(5):
    log_join(Path(sys.argv[1]), participant_name=sys.argv[2])
"""
    processes = []
    try:
        for index in range(4):
            processes.append(subprocess.Popen(
                [sys.executable, "-c", code, str(path), str(index)],
                cwd=Path(__file__).resolve().parents[1], env=dict(os.environ),
                stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
            ))
        for process in processes:
            output, error = process.communicate(timeout=30)
            assert process.returncode == 0, output + error
    finally:
        for process in processes:
            if process.poll() is None:
                process.kill()
                process.wait(timeout=5)
    rows = _rows(path)
    assert len(rows) == 21
    assert len({row["event_id"] for row in rows}) == len(rows)
    assert sum(row["participant_name"] == "Visitor" for row in rows) == 1
